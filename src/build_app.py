"""Rebuild the V4 onedir EXE with its strict matched board identity files."""
from pathlib import Path
import subprocess,sys,json,ssl
from identity import load_identity

root=Path(__file__).resolve().parent
identity=load_identity(root)
manifest=json.loads((root/'native_yuyv.experimental.json').read_text(encoding='utf-8'))
# The offline runner records the source hashes as reproducibility evidence.
# Frozen imports reside inside PYZ; include these sources as explicit data too.
files=set(manifest['files'])|{'native_yuyv.experimental.json',
    'reference.py','reference_v3_frozen.py','geometry.py','auto_v5.py','reference_v5.py','pixels.py','exposure_v4.py',
    'native_pixels_bridge.py','native_pixels/p4_pixels.dll','native_pixels/pixels_native.cpp'}
files.update({'board_runtime.zip','board_runtime.json','board_link.py','jupyter_link.py','session_receipts.py'})
files.add('run_video.py')
files.update({'native/codec.py','native/p4_codec.dll','native/vendor/lz4/LICENSE',
              'native/vendor/lz4/UPSTREAM.json'})
files.update({'native/rice_codec.py','native/y50_native.dll','native/libwinpthread-1.dll'})
files.update({'gui.py','ui_validation.py','physical_ui_validation.py','gui_acceptance.py','launcher.py','transport_quality.py','media_frame.py'})
files.update({'image_controls.py','image_controls_ui.py','image_controls_validation.py'})
files.add('transport_adaptive.py')
files.update({'preview_compare.py','preview_compare_validation.py'})
files.update(p.relative_to(root).as_posix() for p in (root/'comparison_samples').rglob('*') if p.is_file())
# Preserve the public CA policy required by this Python distribution's SSL.
ca_policy=next(Path(ssl.__file__).parent.glob('*-rejected-cas.pem'),None)   # only some Python builds ship one
extra_datas=[(str(ca_policy),'.')] if ca_policy is not None and ca_policy.is_file() else []
spec='''# Generated by build_app.py; no board operations.
from pathlib import Path
root=Path(SPECPATH)
a=Analysis([str(root/'launcher.py')],pathex=[str(root),str(root/'native')],
    binaries=[],datas=[(str(root/name),str(Path(name).parent)) for name in DATAFILES]+EXTRADATAS,hiddenimports=['protocol','codec','rice_codec'],hookspath=[],hooksconfig={},
    runtime_hooks=[],excludes=[],noarchive=False)
pyz=PYZ(a.pure)
exe=EXE(pyz,a.scripts,[],exclude_binaries=True,name='PYNQVideoV4',debug=False,
    bootloader_ignore_signals=False,strip=False,upx=False,console=False)
coll=COLLECT(exe,a.binaries,a.datas,strip=False,upx=False,name='PYNQVideoV4')
'''.replace('DATAFILES',repr(sorted(files))).replace('EXTRADATAS',repr(extra_datas))
(root/'PYNQVideoV4.spec').write_text(spec,encoding='utf-8')
subprocess.run([sys.executable,'-m','PyInstaller','--noconfirm','--clean',
    '--distpath',str(root/'Windows_App'),'--workpath',str(root/'build/app'),str(root/'PYNQVideoV4.spec')],
    cwd=root,check=True)
print(json.dumps(dict(status='BUILT_NOT_GUI_OBSERVED',identity=identity)))
