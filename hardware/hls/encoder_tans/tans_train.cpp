// Train the P6TANS02 ROM tables and evaluate them leave-one-clip-out.
// usage: tans_train LIST OUT_TABLES.h OUT_REPORT.json
//   LIST lines: clip name in.yuyv out.yuyv (1920x1080 YUYV; the FPGA outputs are used)
// Every evaluated frame is encoded with tans_reference.h and decoded back; the
// result must equal nearref's reconstruction. Rice02 sizes come from nearref::encode.
#include "tans_reference.h"
#include <cmath>
#include <cstdio>
#include <fstream>
#include <iterator>
#include <sstream>
using namespace tansref;
static const unsigned W = 1920, H = 1080;
struct Mode { const char* name; unsigned method, shift; };
static const Mode MODES[] = {{"lossless", 3, 0}, {"shift1", 2, 1}};
typedef unsigned short NormT[NTAB][NTOK];

static Bytes load(const std::string& p) { std::ifstream f(p, std::ios::binary); Bytes b((std::istreambuf_iterator<char>(f)), {}); need(b.size() == W * H * 2); return b; }

// Largest-remainder normalisation to L; every symbol a table can be asked for
// keeps a count >= 1 (32 tokens; header tables only k = 0..9).
static void normalise(const std::vector<double>& counts, NormT& out) {
    for (unsigned t = 0; t < NTAB; t++) {
        const unsigned A = t < NRES ? NTOK : NHDR; const double floor = t < NRES ? 1.0 : 0.5;
        double c[NTOK], T = 0; for (unsigned s = 0; s < A; s++) { c[s] = counts[t * NTOK + s] + floor; T += c[s]; }
        unsigned n[NTOK] = {}, sum = 0; std::vector<std::pair<double, unsigned>> rem;
        for (unsigned s = 0; s < A; s++) { double e = c[s] / T * L; n[s] = std::max(1u, unsigned(e)); sum += n[s]; rem.push_back({e - n[s], s}); }
        std::sort(rem.begin(), rem.end(), [](auto& a, auto& b) { return a.first > b.first || (a.first == b.first && a.second < b.second); });
        for (size_t i = 0; sum < L; i = (i + 1) % A) { n[rem[i].second]++; sum++; }
        while (sum > L) { unsigned m = 0; for (unsigned s = 1; s < A; s++) if (n[s] > n[m]) m = s; need(n[m] > 1); n[m]--; sum--; }
        for (unsigned s = 0; s < NTOK; s++) out[t][s] = (unsigned short)n[s];
    }
}

int main(int argc, char** argv) {
    if (argc != 4) { std::fprintf(stderr, "usage: tans_train LIST OUT_TABLES.h OUT_REPORT.json\n"); return 2; }
    struct Item { std::string clip, name, in, out; }; std::vector<Item> items;
    { std::ifstream f(argv[1]); std::string line; while (std::getline(f, line)) { std::istringstream s(line); Item it; if (s >> it.clip >> it.name >> it.in >> it.out) items.push_back(it); } }
    const size_t N = items.size(), M = 2;
    std::vector<std::vector<double>> cnt(N * M); std::vector<size_t> rice(N * M);
    for (size_t f = 0; f < N; f++) {
        Bytes raw = load(items[f].out);
        for (size_t m = 0; m < M; m++) {
            encode(raw, W, H, MODES[m].method, MODES[m].shift, nullptr, nullptr, nullptr, &cnt[f * M + m]);
            rice[f * M + m] = nearref::encode(raw, W, H, MODES[m].method, MODES[m].shift, 1).size();
        }
        std::fprintf(stderr, "counted %s\n", items[f].name.c_str());
    }
    auto train = [&](const std::string& skip_clip, int only_mode, NormT& out) {
        std::vector<double> c(NTAB * NTOK, 0.0);
        for (size_t f = 0; f < N; f++) if (items[f].clip != skip_clip) for (size_t m = 0; m < M; m++) if (only_mode < 0 || int(m) == only_mode)
            for (size_t i = 0; i < c.size(); i++) c[i] += cnt[f * M + m][i];
        normalise(c, out);
    };
    // Production tables: every frame, both modes.
    static NormT prod; train("", -1, prod);
    { std::ofstream o(argv[2]); o << "// Generated by hardware/hls/encoder_tans/tans_train.cpp from " << N << " 1080p frames (lossless + shift 1). Do not edit.\n";
      o << "static const unsigned short NORM[NTAB][NTOK] = {\n";
      for (unsigned t = 0; t < NTAB; t++) { o << "{"; for (unsigned s = 0; s < NTOK; s++) o << prod[t][s] << (s + 1 < NTOK ? "," : ""); o << "}" << (t + 1 < NTAB ? ",\n" : "\n"); }
      o << "};\n"; }
    // Leave-one-clip-out, combined tables and per-mode tables.
    std::ostringstream js; js << "[\n"; bool first = true;
    for (size_t f = 0; f < N; f++) {
        Bytes raw = load(items[f].out);
        static NormT comb, mode_tab[2]; train(items[f].clip, -1, comb); train(items[f].clip, 0, mode_tab[0]); train(items[f].clip, 1, mode_tab[1]);
        for (size_t m = 0; m < M; m++) {
            Bytes restored, wire; unsigned rr = 0, rr2 = 0;
            wire = encode(raw, W, H, MODES[m].method, MODES[m].shift, comb, &restored, &rr);
            need(decode(wire, comb) == restored);
            Bytes w2 = encode(raw, W, H, MODES[m].method, MODES[m].shift, mode_tab[m], nullptr, &rr2);
            Bytes rp = encode(raw, W, H, MODES[m].method, MODES[m].shift, prod);
            js << (first ? "" : ",\n") << "{\"clip\":\"" << items[f].clip << "\",\"name\":\"" << items[f].name << "\",\"mode\":\"" << MODES[m].name
               << "\",\"rice\":" << rice[f * M + m] << ",\"tans_loco_combined\":" << wire.size() << ",\"raw_rows\":" << rr
               << ",\"tans_loco_per_mode\":" << w2.size() << ",\"tans_production\":" << rp.size() << "}";
            first = false;
            std::fprintf(stderr, "%s %s rice %zu loco %zu (%+.4f) per-mode %zu prod %zu raw rows %u\n", items[f].name.c_str(), MODES[m].name, rice[f * M + m], wire.size(),
                         1.0 - double(wire.size()) / rice[f * M + m], w2.size(), rp.size(), rr);
        }
    }
    js << "\n]\n"; std::ofstream(argv[3]) << js.str();
    return 0;
}
